-- Schema de referência do diagrama de classes (PostgreSQL/Supabase).
create table if not exists usuarios (
  id bigint generated by default as identity primary key,
  nome varchar(160) not null,
  email varchar(200) not null unique,
  senha varchar(100) not null,
  tipo varchar(20) not null check (tipo in ('CLIENTE','AGENTE','BANCO')),
  cpf varchar(14), rg varchar(20), endereco varchar(300), profissao varchar(120)
);
create table if not exists rendimentos (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references usuarios(id) on delete cascade,
  empregador varchar(160) not null,
  valor numeric(12,2) not null check (valor >= 0)
);
create table if not exists automoveis (
  id bigint generated by default as identity primary key,
  matricula varchar(30) unique, ano integer not null, marca varchar(80) not null,
  modelo varchar(100) not null, placa varchar(12) not null unique,
  tipo_proprietario varchar(20) not null default 'EMPRESA',
  categoria varchar(100) not null default 'Veículo',
  preco_diaria numeric(10,2) not null default 0,
  imagem varchar(500) not null default '',
  destaque varchar(80) not null default ''
);
alter table automoveis add column if not exists categoria varchar(100) not null default 'Veículo';
alter table automoveis add column if not exists preco_diaria numeric(10,2) not null default 0;
alter table automoveis add column if not exists imagem varchar(500) not null default '';
alter table automoveis add column if not exists destaque varchar(80) not null default '';
create table if not exists pedidos_aluguel (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references usuarios(id),
  veiculo varchar(120) not null,
  data_inicio date not null, data_fim date not null,
  valor_total numeric(12,2) not null check (valor_total >= 0),
  status varchar(20) not null default 'PENDENTE', parecer_financeiro varchar(500), observacao varchar(1000),
  constraint datas_pedido_validas check (data_fim > data_inicio)
);
create table if not exists contratos (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null unique references pedidos_aluguel(id),
  data_contrato date not null default current_date, status varchar(20) not null default 'AGUARDANDO_BANCO'
);
create table if not exists contratos_credito (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null unique references pedidos_aluguel(id),
  banco_id bigint not null references usuarios(id), valor_credito numeric(12,2) not null,
  data_concessao date not null default current_date
);
create index if not exists idx_pedidos_cliente on pedidos_aluguel(cliente_id);
create index if not exists idx_pedidos_status on pedidos_aluguel(status);
